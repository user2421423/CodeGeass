'use strict';
const test=require('node:test'), assert=require('node:assert/strict');
const E=require('../dist/engine.js');
test('War Report initializes at the starting board, aggregates both sides and keeps saves compact',()=>{
  const g=E.createGame('britannia','normal','conquest',123,'world');
  const r=E.ensureWarReport(g);
  assert.equal(r.lastCompleted,0);
  assert.equal(r.snapshots[0].turn,0);
  E.recordWarEvent(g,'cityCaptured','britannia',{city:'Test City',previousOwner:'eu'});
  E.recordWarEvent(g,'unitDestroyed','britannia',{unitSide:'eu',byCombat:true,commander:'leila'});
  E.recordWarEvent(g,'damage','britannia',{targetSide:'eu',value:37});
  E.recordWarEvent(g,'unitProduced','eu',{unitType:'infantry'});
  E.recordWarEvent(g,'income','eu',{credits:45,industry:12});
  E.recordWarEvent(g,'spending','eu',{credits:19,industry:3});
  E.recordWarEvent(g,'fleijaLaunch','britannia',{intercepted:true,defender:'eu'});
  assert.equal(r.turns[1].britannia.citiesCaptured,1);
  assert.equal(r.turns[1].eu.citiesLost,1);
  assert.equal(r.turns[1].britannia.enemiesDestroyed,1);
  assert.equal(r.turns[1].eu.unitsLost,1);
  assert.equal(r.turns[1].eu.commandersLost,1);
  assert.equal(r.turns[1].britannia.inflicted,37);
  assert.equal(r.turns[1].eu.received,37);
  assert.equal(r.turns[1].eu.unitsProduced,1);
  assert.equal(r.turns[1].eu.income.credits,45);
  assert.equal(r.turns[1].eu.spending.credits,19);
  assert.equal(r.turns[1].eu.fleijaIntercepted,1);
  assert.equal(r.events.some(e=>e.kind==='damage'),false);
  E.finishWarTurn(g,1);E.finishWarTurn(g,1);
  assert.equal(r.snapshots.length,2,'idempotent snapshot');
  const packed=E.packSave(g),saved=E.unpackSave(packed);
  assert.deepEqual(saved.warReport,r,'history survives compact saves');
});
test('Pre-War-Report saves start tracking honestly without fabricated past turns',()=>{
  const g=E.createGame('eu','normal','conquest',17,'world');
  delete g.warReport;g.turn=11;
  const r=E.ensureWarReport(g);
  assert.equal(r.since,11);assert.equal(r.legacy,true);
  assert.equal(r.snapshots[0].turn,10);
  assert.equal(r.events.length,0);
});
