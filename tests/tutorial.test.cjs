'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const E = require('../dist/engine.js');
const tutorial = require('../dist/tutorial.js');

test('mechanics tutorial creates an isolated and saveable training battlefield', () => {
  const g = tutorial.create('britannia', 'normal', 1234);
  assert.equal(g.mode, 'scenario');
  assert.equal(g.scenario.id, 'mechanics-tutorial');
  assert.equal(g.cols, 16);
  assert.equal(g.rows, 11);
  assert.equal(g.tiles.length, 176);
  assert.equal(g.scenario.tutorial.step, 0);
  assert.equal(g.stations.length, 3);
  assert.equal(g.units.length, 3);
  assert.equal(g.stations.find(s => s.name === 'Training Depot').shield, 0);
  assert.equal(g.scenario.tutorial.unitId, g.units.find(u => u.side === 'britannia').id);
  assert.equal(E.scenarioOf(g), tutorial);
  assert.equal(tutorial.objective(g).includes('Select a Knightmare'), true);
  assert.equal(tutorial.winner(g), null);
  const loaded = E.unpackSave(E.packSave(g));
  assert.equal(loaded.scenario.tutorial.step, 0);
  assert.equal(loaded.stations.length, 3);
  assert.equal(loaded.tiles.length, g.cols * g.rows);
});
test('the tutorial combat, capture and production goals are actually playable', () => {
  const g = tutorial.create('britannia', 'normal', 1260);
  const trainee = g.units.find(u => u.id === g.scenario.tutorial.unitId);
  const scout = g.units.find(u => u.id === g.scenario.tutorial.scoutId);
  assert(E.reachable(g, trainee).has(E.key({ c: 5, r: 5 })), 'movement hex is reachable');
  assert.equal(E.move(g, trainee.id, 5, 5).ok, true, 'Gloucester can advance');
  assert(E.targets(g, trainee).some(t => t.c === 6 && t.r === 5), 'scout in firing range');
  assert.equal(E.attack(g, trainee.id, 6, 5).ok, true, 'Gloucester can attack');
  assert.equal(scout.hp, 0, 'target has one HP so the lesson cannot require multiple attacks');
  g.turn++;
  E.beginTurn(g, 'britannia', true);
  const move = E.move(g, trainee.id, 7, 5);
  assert.equal(move.ok, true, 'Gloucester can move onto the undefended depot next turn');
  assert.equal(move.captured, 'Training Depot', 'city capture uses normal engine rule');
  const post = g.stations.find(s => s.name === 'Command Post');
  const recruit = E.recruit(g, post.id, 'glasgow', 1);
  assert.equal(recruit.ok, true, recruit.reason || 'player can buy a Knightmare at base');
  assert.equal(recruit.unit.moved, true, 'new unit waits for the next turn');
  assert.equal(recruit.unit.attacked, true, 'new unit cannot immediately fire');
  g.turn++;
  E.beginTurn(g, 'britannia', true);
  assert.equal(recruit.unit.moved, false, 'production unit becomes available after ending turn');
  assert.equal(recruit.unit.attacked, false);
});
