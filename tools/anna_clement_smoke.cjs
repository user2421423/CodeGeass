#!/usr/bin/env node
'use strict';
// Anna Clément: two-hex workshop, half-cost maintenance, action preservation, and no morale aura.
const assert = require('node:assert/strict');
const E = require('../dist/engine.js');
const A = E.COMMANDERS.anna, K = E.COMMANDERS.klaus;
assert.equal(A.fx.annaMaintenance,true);
assert.equal(A.fx.reassure,undefined,'Anna no longer has a morale-recovery bonus');
assert.equal(K.fx.repairSupply,undefined,'Klaus no longer reduces repair costs');
assert.equal(K.fx.fieldSupply,true,'Klaus retains recruitment discounts');
const side='eu', scout=E.typeFor(side,'scout');
const g=E.createGame(side,'normal','conquest',20261020,'world');
g.units=[];
g.phase=side;
Object.assign(g.economy[side],{credits:100000,industry:100000,science:100000,sakuradite:100000});
const open=p=>p&&!E.isSea(p)&&p.terrain==='plains'&&!E.internal.stationAt(g,p);
const farFromCity=p=>g.stations.every(s=>s.owner!==side||E.internal.dist(g,s,p)>3);
const center=g.tiles.find(p=>open(p)&&farFromCity(p)&&E.adjacent(g,p).filter(x=>open(x)&&farFromCity(x)).length>=2);
assert.ok(center,'open, cityless field area');
const candidates=E.adjacent(g,center).filter(p=>open(p)&&farFromCity(p));
const anna=E.newUnit(g,scout,side,center.c,center.r,1,'anna');
const ally=E.newUnit(g,scout,side,candidates[0].c,candidates[0].r,1);
const stranger=E.newUnit(g,scout,side,candidates[1].c,candidates[1].r,1);
assert.ok(E.internal.dist(g,anna,ally)<=2);
assert.equal(E.internal.dist(g,ally,g.stations.find(s=>s.owner===side))>3 || !E.repairReason(g,ally),true);
const half=p=>Object.fromEntries(Object.entries(p).map(([key,value])=>[key,Math.round(value*.5)]));
ally.hp=Math.round(E.maxHP(ally)*.25);
const rein=E.reinforceCost(scout,g,side,ally),discRepair=E.repairCost(ally,g);
anna.expSilenced=true;
const baseRein=E.reinforceCost(scout,g,side,ally),baseRepair=E.repairCost(ally,g);
assert.ok(E.repairReason(g,ally)?.includes('No friendly city nearby'));
delete anna.expSilenced;
assert.deepEqual(rein,half(baseRein),'Anna halves every reinforcement resource');
assert.ok(discRepair<baseRepair,'Anna halves manual repair charges');
const hpBefore=ally.hp;
assert.equal(E.repairReason(g,ally),null,'Anna permits repairs without a city');
assert.equal(E.repair(g,ally.id).ok,true);
assert.equal(ally.hp,hpBefore+Math.round(E.maxHP(ally)*.20));
assert.equal(ally.moved,false,'repair leaves unused move intact');
assert.equal(ally.attacked,false,'repair leaves unused attack intact');
ally.moved=true;ally.attacked=true;ally.hp=Math.floor(E.maxHP(ally)*.3);
assert.equal(E.repair(g,ally.id).ok,true,'repair succeeds after moving and attacking');
assert.equal(ally.moved,true);
assert.equal(ally.attacked,true);
assert.equal(E.reinforceReason(g,ally),null,'Anna permits field frames without a city');
assert.equal(E.reinforce(g,ally.id).ok,true,'frame added after acting');
assert.equal(ally.stack,2);
assert.equal(ally.moved,true,'reinforcement preserves used move status');
assert.equal(ally.attacked,true,'reinforcement preserves used attack status');
stranger.moved=false;stranger.attacked=false;
assert.equal(E.reinforce(g,stranger.id).ok,true,'unacted ally can reinforce');
assert.equal(stranger.moved,false);
assert.equal(stranger.attacked,false);
stranger.stack=3;
assert.ok(E.reinforceReason(g,stranger)?.includes('Already at 3 frames'),'normal frame ceiling remains');
ally.morale=-3;
assert.ok(E.repairReason(g,ally)?.includes('confused'),'confusion is not bypassed');
ally.morale=0;
// Passive field regeneration grants 5% HP without additional morale recovery.
ally.moved=ally.attacked=false;ally.hp=Math.floor(E.maxHP(ally)*.2);ally.morale=-2;
const beforeHP=ally.hp;
E.beginTurn(g,side,false);
assert.ok(ally.hp>=beforeHP+Math.round(E.maxHP(ally)*.05),'Anna regenerates five percent');
assert.equal(ally.morale,-1,'Anna does not add extra morale recovery');
console.log('Anna Clément Rapid Maintenance and Klaus transfer: PASS');
