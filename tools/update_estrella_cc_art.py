#!/usr/bin/env python3
"""Publish the official green Fernando Noriega Estrella for the E.U. close-combat class.

Reference: Hobby Japan's Code Geass: Oz the Reflection editor notes (2014-10-17),
https://hobbyjapan.co.jp/codegeass/season1/extra.html
Source: https://hobbyjapan.co.jp/codegeass/season1/imgs/2014102401.jpg

The source image contains green Fernando (left) and red Marirrosa (right).
Only the green Fernando machine is used here. No game mechanics are changed.
"""
from __future__ import annotations

import hashlib
import io
import json
from collections import deque
from pathlib import Path
from urllib.request import Request, urlopen

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "dist" / "assets" / "art"
URL = "https://hobbyjapan.co.jp/codegeass/season1/imgs/2014102401.jpg"
PAGE = "https://hobbyjapan.co.jp/codegeass/season1/extra.html"


def main() -> None:
    request = Request(URL, headers={"User-Agent": "Mozilla/5.0 (compatible; KnightmareConquest/1.0)"})
    with urlopen(request, timeout=45) as response:
        source_bytes = response.read()
    image = Image.open(io.BytesIO(source_bytes)).convert("RGBA")
    width, height = image.size
    if not (width >= 350 and height >= 350):
        raise RuntimeError(f"Official Estrella image unexpectedly small: {image.size}")

    # Official artwork displays two mechs side by side: Fernando on the left.
    cut_width = round(width * 0.55)
    green = image.crop((0, 0, cut_width, height))
    w, h = green.size
    pixels = green.load()

    # Strip only the white background connected to the cropped picture's
    # outside; don't erase the character's white armor plates.
    visited = bytearray(w * h)
    q = deque()
    def enqueue(x: int, y: int) -> None:
        idx = y * w + x
        if visited[idx]:
            return
        visited[idx] = 1
        r, g, b, _ = pixels[x, y]
        if r >= 236 and g >= 236 and b >= 236:
            q.append((x, y))
    for x in range(w):
        enqueue(x, 0)
        enqueue(x, h - 1)
    for y in range(h):
        enqueue(0, y)
        enqueue(w - 1, y)

    transparent = set()
    while q:
        x, y = q.popleft()
        transparent.add((x, y))
        if x:
            enqueue(x - 1, y)
        if x + 1 < w:
            enqueue(x + 1, y)
        if y:
            enqueue(x, y - 1)
        if y + 1 < h:
            enqueue(x, y + 1)

    for x, y in transparent:
        r, g, b, _ = pixels[x, y]
        pixels[x, y] = (r, g, b, 0)

    box = green.getbbox()
    if not box:
        raise RuntimeError("Unable to extract Fernando Estrella from the official art")
    green = green.crop(box)
    green.thumbnail((512, 512), Image.Resampling.LANCZOS)
    output = io.BytesIO()
    green.save(output, format="PNG", optimize=True)
    png = output.getvalue()
    if len(png) < 12000:
        raise RuntimeError(f"Unexpectedly small replacement image: {len(png)} bytes")
    digest = hashlib.sha256(png).hexdigest()[:12]
    filename = f"estrella_cc_fernando-{digest}.png"
    dest = ART / "units" / filename
    dest.write_bytes(png)

    manifest_path = ART / "manifest.json"
    manifest = json.loads(manifest_path.read_text("utf-8"))
    standard_before = manifest["units"]["estrella"]["src"]
    replacement_before = manifest["units"]["estrella_cc"]["src"]
    manifest["units"]["estrella_cc"]["src"] = "units/" + filename
    dumped = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    manifest_path.write_text(dumped, encoding="utf-8")
    (ART / "manifest.js").write_text(
        "// Generated by tools/publish_art.py; edit manifest.json through the publisher.\n"
        + "globalThis.KnightmareArtManifest = " + dumped.rstrip() + ";\n",
        encoding="utf-8",
    )
    sources_path = ART / "sources.json"
    sources = json.loads(sources_path.read_text("utf-8"))
    for record in sources["retrieved"].values():
        if record.get("kind") == "units" and record.get("id") == "estrella_cc":
            record["file"] = "units/" + filename
            record["page"] = PAGE
            record["image"] = URL
            record["method"] = (
                "Official Hobby Japan Oz the Reflection color-reference art: "
                "Fernando Noriega green Estrella cropped from the left half; "
                "connected white background removed for transparent game sprite."
            )
            break
    else:
        raise RuntimeError("Estrella Close-Combat asset source record is missing")
    sources_path.write_text(json.dumps(sources, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    assert manifest["units"]["estrella"]["src"] == standard_before
    assert replacement_before != manifest["units"]["estrella_cc"]["src"]
    print(f"Estrella stays {standard_before}; Estrella Close-Combat now {filename} ({green.size}, {len(png)} bytes)")
    print("Official source: " + URL)


if __name__ == "__main__":
    main()
