#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const E = require('../dist/engine.js');
const side = 'britannia';
const g = E.createGame(side, 'normal', 'conquest', 20261018, 'world');
g.phase = side;
g.economy[side].credits = 100000;
g.economy[side].industry = 100000;
g.units = [];
const s = g.stations.find(v => v.owner === side && !v.capital && !v.fort && v.tier === 1);
assert.ok(s, 'Conquest starts with an ordinary level-one city');
assert.equal(E.cityTierOf(s), 1);
assert.equal(s.maxShield, 200);
const industry = s.industry;
assert.equal(E.build(g, s.id, 'factory').ok, true);
assert.equal(s.maxShield, 200, 'Factory upgrades cannot change defense HP');
assert.equal(s.industry, industry + 10);
assert.equal(E.cityTierOf(s), 1, 'City Tier stays independent of factory level');
s.shield = 160;
const income = s.income;
assert.equal(E.upgradeCityTier(g, s.id).ok, true);
assert.equal(s.cityTier, 2);
assert.equal(s.tier, 2, 'Factory level is unaffected by City Tier upgrade');
assert.equal(s.income, income + 8);
assert.equal(s.maxShield, 250);
assert.equal(s.shield, 160, 'No instant HP recovery from upgrading');
assert.equal(E.upgradeCityTier(g, s.id).ok, false, 'Maximum one tier upgrade each turn');
g.turn++;
assert.equal(E.upgradeCityTier(g, s.id).ok, true);
assert.equal(s.cityTier, 3);
assert.equal(s.income, income + 18);
assert.equal(s.maxShield, 300);
g.turn++;
assert.equal(E.upgradeCityTier(g, s.id).ok, true);
assert.equal(s.cityTier, 4);
assert.equal(s.fort, true);
assert.equal(s.maxShield, 400);
assert.ok(s.gun);
assert.equal(E.fortressReady(g, s), false, 'Battery cannot fire on purchase turn');
g.turn++;
assert.equal(E.fortressReady(g, s), true, 'Battery becomes available next turn');
assert.equal(E.upgradeCityTier(g, s.id).ok, false, 'Fortress is maximum tier');
assert.ok(g.stations.some(v => v.capital && v.owner === side && v.maxShield >= 600));
console.log('Direct city tiers and factory separation: PASS');
