#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const ai = read('src/ai/07-tactical-orders.part.js');
const notifications = read('dist/ui/notifications.js');
const input = read('dist/ui/input.js');
const turns = read('dist/ui/turns.js');
const css = read('dist/battlefield.css');
const engine = require('../dist/engine.js');
assert.equal(engine.COMMANDERS.zero.action.name, 'Geass Absolute Command');
assert.match(ai, /function zeroCommandTarget\(g, u\)/);
assert.match(ai, /const allies = options\.filter\(v => v\.side === u\.side\)/);
assert.match(ai, /const enemies = options\.filter\(v => foe\(g, v\.side, u\.side\)\)/);
assert.match(ai, /u\.cmd === 'zero' \? zeroCommandTarget\(g, u\) : null/);
assert.match(ai, /feint\(g, id, chosen\?\.id\)/);
assert.match(ai, /refreshed && refreshed\.side === u\.side/);
assert.match(notifications, /game\?\.mode === 'campaign' \|\| \(game\?\.mode === 'scenario' && !!game\.warCampaign\)/);
assert.match(notifications, /if \(!c\?\.action\) return/);
assert.match(notifications, /abilityBannerTimeout = setTimeout\(\(\) => \{/);
assert.match(notifications, /\}, 1000\)/);
assert.match(notifications, /function useCommanderAbility\(unitId, targetId = null\)/);
assert.match(notifications, /if \(result\?\.ok && unit\?\.cmd\) announceCommanderAbility\(unit\.cmd\)/);
assert.match(input, /useCommanderAbility\(u\.id, \+d\.command\)/);
assert.match(input, /useCommanderAbility\(u\.id\)/);
assert.match(turns, /if \(o\.kind === 'feint'\)/);
assert.match(turns, /announceCommanderAbility\(actor\.cmd\)/);
assert.match(css, /\.commander-ability-banner\.visible/);
assert.match(css, /\.commander-ability-banner\[hidden\]/);
console.log('Commander active banners and Zero AI target selection: PASS');
