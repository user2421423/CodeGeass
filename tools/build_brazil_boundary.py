#!/usr/bin/env python3
"""Embed Brazil's Natural Earth 1:50m border and exclude neighbouring land.

Input: ne_50m_admin_0_countries.geojson from natural-earth-vector.
The country outline clips artwork; the mask excludes foreign ground without
changing Brazil's GSHHG shoreline or the Atlantic invasion approaches.
"""
import base64
import json
from pathlib import Path
import re
import sys

COLS, ROWS = 176, 144
WEST, EAST, NORTH, SOUTH = -81, -31, 9, -36
DEST = Path(__file__).resolve().parents[1] / 'dist/scenarios-brazil.js'


def main():
    features = json.loads(Path(sys.argv[1]).read_text())['features']
    brazil = next(f for f in features if f['properties']['ADMIN'] == 'Brazil')
    polygons = brazil['geometry']['coordinates']
    rings = [p[0] for p in polygons]
    # Cache row intersections. Odd/even ray crossings avoid a heavyweight GIS
    # dependency and retain every supplied country-border control point.
    crossings = {}

    def inside(lon, lat):
        if lat not in crossings:
            xs = []
            for ring in rings:
                for a, b in zip(ring, ring[1:]):
                    if (a[1] > lat) != (b[1] > lat):
                        xs.append(a[0] + (lat-a[1])*(b[0]-a[0])/(b[1]-a[1]))
            crossings[lat] = sorted(xs)
        xs = crossings[lat]
        return any(a <= lon <= b for a, b in zip(xs[::2], xs[1::2]))

    bits = bytearray((COLS*ROWS+7)//8)
    for r in range(ROWS):
        for c in range(COLS):
            lon = WEST+(c+.5+.5*(r & 1))*(EAST-WEST)/COLS
            lat = NORTH-(r+.5)*(NORTH-SOUTH)/ROWS
            # Keep hex footprints intersecting Brazil, including frontier cities.
            samples = [(0, 0), (-.48, 0), (.48, 0),
                       (-.24, -.48), (.24, -.48), (-.24, .48), (.24, .48)]
            if not any(inside(lon+dx*(EAST-WEST)/COLS,
                              lat+dy*(NORTH-SOUTH)/ROWS) for dx, dy in samples):
                i = r*COLS+c
                bits[i >> 3] |= 128 >> (i & 7)
    block = ('  // Natural Earth 1:50m admin-0 Brazil, public domain; generated by\n'
             '  // tools/build_brazil_boundary.py. Drawing border and tactical mask are separate.\n'
             '  const BRAZIL_LAND='+json.dumps(rings, separators=(',', ':'))+';\n'
             "  const OUTSIDE_BRAZIL=atob('"+base64.b64encode(bits).decode()+"');\n")
    source = DEST.read_text()
    pattern = r'  // BEGIN BRAZIL BOUNDARY\n.*?  // END BRAZIL BOUNDARY\n'
    replacement = '  // BEGIN BRAZIL BOUNDARY\n'+block+'  // END BRAZIL BOUNDARY\n'
    if re.search(pattern, source, re.S):
        source = re.sub(pattern, lambda _: replacement, source, flags=re.S)
    else:
        source = source.replace('  const CITIES=', replacement+'  const CITIES=', 1)
    DEST.write_text(source)
    print('Brazil border:', len(rings), 'polygons;', sum(b.bit_count() for b in bits), 'outside footprints')


if __name__ == '__main__':
    main()
