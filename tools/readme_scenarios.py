#!/usr/bin/env python3
"""Regenerate the README's regional scenario table from the scenario manifest.

Order, menu titles and notes come from dist/scenario-manifest.js; map size and the
one-line intro come from dist/scenario-catalog.js (tools/generate-scenario-catalog.cjs).
Run after adding or changing a scenario. --check exits 1 when the README is stale.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / 'README.md'
START, END = '<!-- scenarios:start -->', '<!-- scenarios:end -->'


def table():
    manifest = (ROOT / 'dist/scenario-manifest.js').read_text()
    entries = re.findall(r'\{id:"([^"]+)",title:"([^"]+)",note:"([^"]+)"\}', manifest)
    src = (ROOT / 'dist/scenario-catalog.js').read_text()
    catalog = json.loads(src[src.index('Object.freeze(') + len('Object.freeze('):src.rindex(')')])
    missing = [i for i, _, _ in entries if i not in catalog]
    if not entries or missing:
        sys.exit('Scenario manifest and catalog disagree: ' + ', '.join(missing or ['no manifest entries']))
    rows = [f'{len(entries)} scenarios, in menu order (generated by `python3 tools/readme_scenarios.py`):', '',
            '| Scenario | Battlefield | Starting situation and objective |', '| --- | --- | --- |']
    for i, title, note in entries:
        c = catalog[i]
        intro = c['meta']['text'].get('intro', '').replace('|', '\\|')
        rows.append(f"| **{title}** | {c['cols']} × {c['rows']} · {note} | {intro} |")
    return '\n'.join(rows)


def main():
    text = README.read_text()
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f'{head}{START}\n{table()}\n{END}{tail}'
    if '--check' in sys.argv:
        if new != text:
            sys.exit('README.md scenario table is stale: run python3 tools/readme_scenarios.py')
        return
    README.write_text(new)


main()
