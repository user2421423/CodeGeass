#!/usr/bin/env node
'use strict';
// Offline GSHHG polygon identity audit. Mixed shore cells may not join two
// distinct islands. The world atlas ends at 74N; preserve the dedicated
// Canadian Arctic mask and anchors beyond that source boundary.
// Keep the original regional grids and open a sea cell on
// the weaker sampled shore where different geographic polygons touch.
const fs=require('node:fs'),vm=require('node:vm');
const atlas=vm.runInNewContext(fs.readFileSync('dist/ui/geography-data.js','utf8')+';GEOGRAPHY_SHAPES.land');
const phil=require('./data/coast.json').philippines;
const E=require('../dist/engine.js');
function contains(x,y,p){let inside=false;for(let i=0,j=p.length-1;i<p.length;j=i++){
 const a=p[i],b=p[j];if((a[1]>y)!=(b[1]>y)&&x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0])inside=!inside;}return inside;}
function bounds(p){return [Math.min(...p.map(x=>x[0])),Math.min(...p.map(x=>x[1])),Math.max(...p.map(x=>x[0])),Math.max(...p.map(x=>x[1]))];}
function refine(cfg){
 const {w,h,west,east,north,south,polygons,base,region,cities}=cfg,dx=(east-west)/w,dy=(north-south)/h;
 const geo=(c,r)=>[west+(c+.5*(r&1)+.5)*dx,north-(r+.5)*dy];
 const shapes=polygons.map((p,id)=>({p,id:id+1,b:bounds(p)})).filter(s=>s.b[2]>=west&&s.b[0]<=east&&s.b[3]>=south&&s.b[1]<=north);
 const nearby=(x,y)=>shapes.filter(s=>s.b[0]<=x+dx&&s.b[2]>=x-dx&&s.b[1]<=y+dy&&s.b[3]>=y-dy);
 const which=(x,y,ss)=>ss.find(s=>x>=s.b[0]&&x<=s.b[2]&&y>=s.b[1]&&y<=s.b[3]&&contains(x,y,s.p))?.id||0;
 const labels=new Int16Array(w*h),solid=new Float32Array(w*h),coverage=Uint8Array.from(base);
 for(let r=0;r<h;r++)for(let c=0;c<w;c++){
  const i=r*w+c,[x,y]=geo(c,r);if(!region(x,y))continue;
  const ss=nearby(x,y),votes=new Map();let n=0;
  for(const ox of [-.4,-.2,0,.2,.4])for(const oy of [-.4,-.2,0,.2,.4]){
   const id=which(x+ox*dx,y+oy*dy,ss);if(id){votes.set(id,(votes.get(id)||0)+1);n++;}}
  const center=which(x,y,ss),best=[...votes].sort((a,b)=>b[1]-a[1]||a[0]-b[0])[0];
  if(cfg.raster)coverage[i]=n<5?0:n<=20?1:2;
  if(!coverage[i])continue;
  labels[i]=center||best?.[0]||0;solid[i]=n/25;
 }
 const cityIslands={};const pins=new Set();
 for(const [name,lon,lat] of cities){if(!region(lon,lat))continue;
  const ss=nearby(lon,lat);let island=which(lon,lat,ss);
  // Shoreline city coordinates can lie just outside the polygon. Use the
  // closest actual polygon sample, never the nearest already-merged landmass.
  if(!island){let d=Infinity;for(const s of (ss.length?ss:shapes))for(const [x,y] of s.p){const v=((x-lon)/dx)**2+((y-lat)/dy)**2;if(v<d){d=v;island=s.id}}}
  cityIslands[name]=island;let best=null,d=Infinity;
  for(let i=0;i<labels.length;i++)if(labels[i]===island&&coverage[i]){
   const [x,y]=geo(i%w,(i/w)|0),v=((x-lon)/dx)**2+((y-lat)/dy)**2;
   if(v<d){d=v;best=i;}}
  if(best!=null)pins.add(best);
 }
 const g={cols:w,rows:h,tiles:Array.from(coverage,(v,i)=>({c:i%w,r:(i/w)|0}))};
 const importantIslands=new Set(Object.values(cityIslands));importantIslands.delete(cityIslands.Vancouver || 0);
 const priority=k=>solid[k]+(pins.has(k)?2:0)+(importantIslands.has(labels[k])?10:0);
 const labelCounts=new Map();for(let i=0;i<labels.length;i++)if(coverage[i]&&labels[i])labelCounts.set(labels[i],(labelCounts.get(labels[i])||0)+1);
 let changed=true;while(changed){changed=false;
  for(let i=0;i<coverage.length;i++)if(coverage[i]&&labels[i])for(const n of E.adjacent(g,g.tiles[i])){
   const j=n.r*w+n.c;if(j<=i||!coverage[j]||!labels[j]||labels[i]===labels[j])continue;
   const candidates=[i,j].filter(k=>(labelCounts.get(labels[k])||0)>1||!pins.has(k)).sort((a,b)=>priority(a)-priority(b)||a-b);
   if(!candidates.length)throw Error('Two city anchors need a finer strait: '+i+'/'+j);
   const k=candidates[0];labelCounts.set(labels[k],labelCounts.get(labels[k])-1);coverage[k]=0;labels[k]=0;changed=true;
  }
 }
 const changes=[];for(let i=0;i<coverage.length;i++)if(coverage[i]!==base[i])changes.push([i%w,(i/w)|0,coverage[i]]);
 const runs=[];for(let i=0;i<labels.length;){const id=labels[i];let j=i+1;while(j<labels.length&&labels[j]===id)j++;if(id)runs.push([i,j-i,id]);i=j;}
 return {changes,runs,cityIslands};
}
const canadaFile='dist/canada-landmask.js',canadaText=fs.readFileSync(canadaFile,'utf8');
const bytes=Buffer.from(canadaText.match(/const DATA = '([^']+)'/)[1],'base64'),coverage=[];
for(const b of bytes)for(let j=0;j<(b&63)+1;j++)coverage.push(b>>6);
const canada=require('../dist/scenarios-canada.js');
const ca=refine({w:196,h:112,west:-147,east:-40,north:83.8,south:41,polygons:atlas,base:coverage,region:(x,y)=>y<73.5,cities:canada.cityData});
const canadaCode=`\n  // Generated by tools/refine-island-coasts.cjs from the GSHHG atlas.\n  const islandRuns=${JSON.stringify(ca.runs)};\n  const islands=new Int16Array(coverage.length);\n  for(const [start,count,id] of islandRuns)islands.fill(id,start,start+count);\n  for(const [c,r,kind] of ${JSON.stringify(ca.changes)})coverage[r*196+c]=kind;\n  const cityIslands=${JSON.stringify(ca.cityIslands)};\n`;
let clean=canadaText.replace(/\n(?:[ \t]*\n)*  \/\/ Generated by tools\/refine-island-coasts[\s\S]*?(?=  const api=)/,'\n');
clean=clean.replace('  const api=',canadaCode+'  const api=').replace(/south:41,coverage(?:,islands,cityIslands)*/, 'south:41,coverage,islands,cityIslands');
fs.writeFileSync(canadaFile,clean);
const phFile='dist/philippines-landmask.js',phText=fs.readFileSync(phFile,'utf8');const raw=require('./philippines_landmask_builder.cjs').baseBits;
const phBase=Array.from({length:144*112},(_,i)=>(raw[i>>3]&(128>>(i&7)))?2:0);
const philippines=require('../dist/scenarios-philippines.js');
const ph=refine({w:144,h:112,west:115.5,east:139.1,north:21.2,south:4.5,polygons:phil,base:phBase,raster:true,region:(x,y)=>x>121.8&&x<124.8&&y>8.8&&y<12.2,cities:philippines.cityData});
const packed=Buffer.from(raw);for(const [c,r,kind] of ph.changes){const i=r*144+c;if(kind)packed[i>>3]|=128>>(i&7);else packed[i>>3]&=~(128>>(i&7));}
let phClean=phText.replace(/const bits = '[^']+'/,'const bits = '+JSON.stringify(packed.toString('base64'))).replace(/\n  \/\/ Generated by tools\/refine-island-coasts[\s\S]*?(?=  root.PHILIPPINES_LAND_BITS)/,'\n');
phClean=phClean.replace('  root.PHILIPPINES_LAND_BITS',`  // Generated by tools/refine-island-coasts.cjs; island-aware city anchors.\n  const islands=new Int16Array(144*112);\n  for(const [start,count,id] of ${JSON.stringify(ph.runs)})islands.fill(id,start,start+count);\n  root.PHILIPPINES_GEOGRAPHY={islands,cityIslands:${JSON.stringify(ph.cityIslands)}};\n  root.PHILIPPINES_LAND_BITS`);
// Keep the bitmap's longstanding single-quoted source convention.
phClean=phClean.replace(/const bits = "([^"]+)"/,"const bits = '$1'");
fs.writeFileSync(phFile,phClean);
fs.writeFileSync('tools/data/island-coast-refinements.json',JSON.stringify({source:'GSHHG polygon identities; 25 footprint samples per tile',canada:ca.changes,philippines:ph.changes},null,2)+'\n');
console.log('Island refinements',JSON.stringify({canada:ca.changes.length,philippines:ph.changes.filter(x=>!!phBase[x[1]*144+x[0]]!==!!x[2]).length,canadianCityIslands:ca.cityIslands,philippineCityIslands:ph.cityIslands}));
